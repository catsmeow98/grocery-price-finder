# Items a store does not carry (tests "missing at some stores"); only these skip rows.
ONLY_AT = {("Frozen Pizza","Prairie Farms"):[0,1], ("Ground Coffee","Prairie Farms"):[0,2]}
OUT_OF_STOCK = {("Bacon","Harvest Pride",16,3)}  # (name, brand, qty, store index)

def q(s): return "'" + str(s).replace("'", "''") + "'"
out = []
out.append("-- 02_sample_data.sql  (generated by scripts/make_sample_data.py)\n"
           "-- Run in Supabase SQL Editor. Safe to re-run (fixed ids + ON CONFLICT DO NOTHING).\n"
           "-- Remove everything later with 03_remove_sample_data.sql.\n")
rows = []
for i, (n, a, c, z, f) in enumerate(STORES):
    rows.append(f"({q(uid('store', n))}, {q(n)}, {q(c)}, {q(a)}, 'MI', {z}, now())")
out.append("insert into public.stores (id, name, city, address, state, zip, created_at) values\n" + ",\n".join(rows) + "\non conflict (id) do nothing;\n")

prows = []; seen = set()
for (n, b, qty, u, t, base) in P:
    pid = uid('product', n, b, qty, u)
    upc = "SAMPLE-" + pid[:8].upper()
    prows.append(f"({q(pid)}, {q(n)}, {q(b)}, {qty}, {q(u)}, {q(t)}, {q(upc)}, now())")
out.append('insert into public.products (id, name, brand, quantity, unit, unit_type, "UPC", updated_at) values\n' + ",\n".join(prows) + "\non conflict (id) do nothing;\n")

rrows = []
for (n, b, qty, u, t, base) in P:
    pid = uid('product', n, b, qty, u)
    for si, (sn, *_rest, f) in enumerate(STORES):
        allowed = ONLY_AT.get((n, b))
        if allowed is not None and si not in allowed: continue
        price = round(base * f * (0.93 + 0.14 * h(n, b, qty, si)), 2)
        sale = round(price * 0.85, 2) if h('sale', n, b, qty, si) < 0.15 else None
        avail = "false" if (n, b, qty, si) in OUT_OF_STOCK else "true"
        sid = uid('store', sn)
        sale_sql = "null" if sale is None else f"{sale:.2f}"
        rrows.append(f"({q(uid('price', pid, sid, 'now'))}, {q(pid)}, {q(sid)}, {price:.2f}, {sale_sql}, {avail}, now(), 'sample', now())")
        # older, higher observation on ~1/3 of rows: tests "newest price wins" and builds history
        if h('old', n, b, qty, si) < 0.33:
            rrows.append(f"({q(uid('price', pid, sid, 'old'))}, {q(pid)}, {q(sid)}, {price*1.1:.2f}, null, true, now() - interval '30 days', 'sample', now() - interval '30 days')")
out.append("insert into public.prices (id, product_id, store_id, price, sale_price, available, observed_at, source, created_at) values\n" + ",\n".join(rrows) + "\non conflict (id) do nothing;\n")
open("supabase/02_sample_data.sql", "w").write("\n".join(out))
print(len(P), "products,", len(STORES), "stores,", len(rrows), "price rows")
