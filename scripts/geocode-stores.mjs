// scripts/geocode-stores.mjs
//
// Finds latitude/longitude for store locations that don't have them yet and
// writes supabase/11_store_coordinates.sql for you to run in Supabase.
//
// Run from the project folder:   node scripts/geocode-stores.mjs
//
// It uses the free US Census geocoder (no account or key needed) and reads
// your Supabase URL and public key from .env.local. Sample stores are skipped
// (they get coordinates from 02_sample_data.sql).

import { readFileSync, writeFileSync } from "node:fs";

function readEnv() {
  const env = {};

  for (const line of readFileSync(".env.local", "utf8").split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);

    if (match) {
      env[match[1]] = match[2].replace(/^["']|["']$/g, "");
    }
  }

  return env;
}

const env = readEnv();
const url = env.NEXT_PUBLIC_SUPABASE_URL;
const key = env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

if (!url || !key) {
  console.error(
    "Could not find NEXT_PUBLIC_SUPABASE_URL / NEXT_PUBLIC_SUPABASE_ANON_KEY in .env.local"
  );
  process.exit(1);
}

const response = await fetch(
  `${url}/rest/v1/stores?select=id,name,address,city,state,zip&latitude=is.null&name=not.like.Sample*&order=name`,
  { headers: { apikey: key, Authorization: `Bearer ${key}` } }
);

if (!response.ok) {
  console.error(
    `Could not read your stores (${response.status}). Has supabase/10_locations.sql been run?`
  );
  process.exit(1);
}

const stores = await response.json();

if (stores.length === 0) {
  console.log("Every store already has coordinates. Nothing to do.");
  process.exit(0);
}

const lines = [
  "-- 11_store_coordinates.sql (generated by scripts/geocode-stores.mjs)",
  "-- Run in Supabase SQL Editor.",
  "",
];

let found = 0;

for (const store of stores) {
  const address = [
    store.address,
    store.city,
    `${store.state ?? ""} ${store.zip ?? ""}`.trim(),
  ]
    .filter(Boolean)
    .join(", ");

  const geocodeUrl =
    "https://geocoding.geo.census.gov/geocoder/locations/onelineaddress" +
    `?address=${encodeURIComponent(address)}&benchmark=Public_AR_Current&format=json`;

  let match = null;

  try {
    const result = await fetch(geocodeUrl);
    const data = await result.json();

    match = data?.result?.addressMatches?.[0] ?? null;
  } catch (error) {
    console.error(`  ${store.name} - lookup failed: ${error.message}`);
  }

  if (match && match.coordinates) {
    const lat = Number(match.coordinates.y);
    const lng = Number(match.coordinates.x);

    lines.push(
      `update public.stores set latitude = ${lat}, longitude = ${lng} where id = '${store.id}'; -- ${store.name}, ${address}`
    );

    console.log(`  found     ${store.name}, ${address}`);
    found++;
  } else {
    lines.push(`-- NOT FOUND: ${store.name}, ${address}`);

    console.log(`  not found ${store.name}, ${address}`);
  }

  // be polite to the free service
  await new Promise((resolve) => setTimeout(resolve, 300));
}

writeFileSync("supabase/11_store_coordinates.sql", lines.join("\n") + "\n");

console.log(
  `\n${found} of ${stores.length} stores located. Now paste supabase/11_store_coordinates.sql into the Supabase SQL Editor and click Run.`
);
