"""Generates supabase/02_sample_data.sql (deterministic, re-runnable).

Usage: python3 scripts/make_sample_data.py
All sample rows are tagged so they can be removed (see 03_remove_sample_data.sql):
  prices.source = 'sample', products."UPC" starts with 'SAMPLE-', stores named 'Sample ...'
"""
import hashlib, uuid

def uid(*parts):
    return str(uuid.UUID(hashlib.md5("|".join(map(str, parts)).encode()).hexdigest()))

def h(*parts):  # deterministic number 0..1
    return int(hashlib.md5("|".join(map(str, parts)).encode()).hexdigest()[:8], 16) / 0xFFFFFFFF

